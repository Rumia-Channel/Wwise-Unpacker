def id_candidates(stem: str) -> List[Tuple[int, str]]:
    """Possible Wwise IDs a file stem may encode (decimal/hex, 32/64-bit)."""
    out: List[Tuple[int, str]] = []
    if DEC_RE.match(stem):
        value = int(stem)
        if value < 0:
            out.append((value + 2 ** 32, "dec(signed)"))
        elif value <= MASK32:
            out.append((value, "dec"))
        # many tools write zero-padded hex ("0000abcd", "01234567")
        if len(stem) > 8 and stem.isdigit():
            out.append((int(stem, 16), "hex(padded64)"))
        elif len(stem) >= 6 and stem.startswith("0"):
            out.append((int(stem, 16), "hex(padded)"))
    m = HEX_RE.match(stem)
    if m and re.search(r"[a-fA-F]", m.group(1)):
        out.append((int(m.group(1), 16), "hex"))
    else:
        m64 = HEX64_RE.match(stem)
        if m64:
            out.append((int(m64.group(1), 16), "hex64"))
    return out


def pick_entry(candidates: Sequence[Entry], ext: str) -> Tuple[Entry, List[str]]:
    pref = PREF_WEM if ext == "wem" else PREF_BNK if ext == "bnk" else PREF_OTHER
    ordered = sorted(candidates, key=lambda e: pref.index(e.kind) if e.kind in pref else 99)
    best = ordered[0]
    alts = [f"{e.name} ({e.kind}, {e.source})" for e in ordered[1:] if e.name != best.name]
    return best, alts


def sanitize(name: str) -> str:
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip().rstrip(". ")
    return name


def build_plan(audio_dir: Path, mapping: Dict[int, List[Entry]], exts: Sequence[str],
               recursive: bool, keep_paths: bool = True
               ) -> Tuple[List[Plan], int, List[Tuple[Path, int, str]]]:
    plans: List[Plan] = []
    skipped_named = 0
    unresolved: List[Tuple[Path, int, str]] = []

    it = audio_dir.rglob("*") if recursive else audio_dir.glob("*")
    for path in sorted(it):
        if not path.is_file() or path.suffix.lower().lstrip(".") not in exts:
            continue
        cands = id_candidates(path.stem)
        if not cands:
            skipped_named += 1
            continue
        hit = next(((value, style) for value, style in cands if mapping.get(value)), None)
        if hit is None:
            unresolved.append((path, cands[0][0], cands[0][1]))
            continue
        value, style = hit
        ext = path.suffix.lower().lstrip(".")
        best, alts = pick_entry(mapping[value], ext)
        rel = best.relpath if (keep_paths and best.relpath) else None
        plans.append(Plan(path, value, style, sanitize(best.name), best.source, best.kind, alts, rel))
    return plans, skipped_named, unresolved


def _target_for(plan: Plan, root: Path) -> Path:
    if plan.relpath:
        parts = [sanitize(p) for p in Path(plan.relpath).parent.parts if p not in (".", "")]
        return root.joinpath(*parts, f"{plan.name}{plan.path.suffix}") if parts \
            else root / f"{plan.name}{plan.path.suffix}"
    return plan.path.with_name(f"{plan.name}{plan.path.suffix}")


def apply_plan(plans: Sequence[Plan], apply: bool, root: Path) -> Tuple[int, int, List[str]]:
    renamed = 0
    conflicts = 0
    errors: List[str] = []
    used: Dict[Path, Path] = {}
    for plan in plans:
        target = _target_for(plan, root)
        taken = used.get(target)
        if target.exists() or taken is not None:
            n = 2
            while True:
                cand = target.with_name(f"{plan.name} ({n}){plan.path.suffix}")
                if not cand.exists() and cand not in used:
                    target = cand
                    break
                n += 1
            conflicts += 1
        if target == plan.path:
            continue
        used[target] = plan.path
        if apply:
            try:
                target.parent.mkdir(parents=True, exist_ok=True)
                plan.path.rename(target)
            except OSError as exc:
                errors.append(f"{plan.path.name}: {exc}")
                continue
        renamed += 1
    return renamed, conflicts, errors


