#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Rename Wwise-extracted files (<ShortID>.<ext>) to their in-game names.

Wwise references everything by 32-bit ShortID, so extracted .wem/.bnk files are
usually named like "43388703.wem". This tool maps those IDs back to readable
names using whatever metadata is available:

  * SoundbanksInfo.xml (Wwise-generated: original media paths, event names,
    soundbank names; gives exact original file names)
  * Wwise_IDs.h        (C++ header with NAME = ID constants)
  * (bank).txt         (tab/space separated ID/name lists, best effort)
  * wwnames.txt        (candidate name list; IDs resolved by computing the
    Wwise FNV-1 32-bit hash of each name)
  * *.txtp             (files generated by wwiser; .wem IDs referenced inside
    are named after the event in the .txtp file name)

Media (.wem) IDs are FNV hashes of editor GUIDs, so they are NOT recoverable
from name lists; only SoundbanksInfo.xml / bank .txt / Wwise_IDs.h contain the
original media file names. Event/bank/etc names are FNV-1 hashes of their
lowercase names and can be recovered from a candidate list (wwiser-utils'
"wwnames" has prebuilt lists for 250+ games).

Usage:
  python wwise_names.py SoundbanksInfo.xml wwnames.txt --audio-dir Decoding --dry-run
  python wwise_names.py SoundbanksInfo.xml --audio-dir OGG --apply
  python wwise_names.py --fetch-wwnames "Life is Strange"   # saves wwnames.txt

Renaming is a dry-run unless --apply is given.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
import urllib.parse
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

MASK32 = 0xFFFFFFFF
MASK64 = 0xFFFFFFFFFFFFFFFF
FNV_OFFSET = 0x811C9DC5
FNV_PRIME = 0x01000193
FNV64_OFFSET = 0xCBF29CE484222325
FNV64_PRIME = 0x100000001B3

DEFAULT_EXTS = "wem,ogg,mp3,wav,xma,logg,lwav,bnk"
NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
DEC_RE = re.compile(r"^-?\d+$")
HEX_RE = re.compile(r"^(?:0x)?([0-9a-fA-F]{1,8})$")
HEX64_RE = re.compile(r"^(?:0x)?([0-9a-fA-F]{9,16})$")
EXT_PATH_RE = re.compile(r"^[^\s:]+\.wem$", re.IGNORECASE)
HASH_SUFFIX_RE = re.compile(r"_[0-9A-Fa-f]{8}$")

WWNAMES_API = "https://api.github.com/repos/bnnm/wwiser-utils/contents/wwnames"
WWNAMES_RAW = "https://raw.githubusercontent.com/bnnm/wwiser-utils/master/wwnames/"

# preference when several sources know the same ID (per target extension)
PREF_WEM = ("external", "media", "event", "bank", "wwnames", "txtp", "txtp-index")
PREF_BNK = ("bank", "event", "media", "external", "wwnames", "txtp", "txtp-index")
PREF_OTHER = ("event", "txtp", "external", "media", "bank", "wwnames", "txtp-index")


def fnv1_32(data: bytes) -> int:
    h = FNV_OFFSET
    for b in data:
        h = (h * FNV_PRIME) & MASK32
        h ^= b
    return h


def wwise_hash(name: str) -> int:
    """Wwise ShortID for a hashname: FNV-1 32-bit of the lowercase name."""
    return fnv1_32(name.lower().encode("utf-8"))


def wwise_external_hash(path: str) -> int:
    """Wwise external-source ID: FNV-1 64-bit of the lowercase path."""
    h = FNV64_OFFSET
    for b in path.lower().encode("utf-8"):
        h = (h * FNV64_PRIME) & MASK64
        h ^= b
    return h


@dataclass
class Entry:
    id: int
    name: str
    source: str
    kind: str  # media | event | bank | wwnames | txtp | external
    relpath: Optional[str] = None  # original relative path (externals)


@dataclass
class Plan:
    path: Path
    id: int
    id_style: str
    name: str
    source: str
    kind: str
    alternatives: List[str] = field(default_factory=list)
    relpath: Optional[str] = None


