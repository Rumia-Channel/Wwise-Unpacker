def read_text_any(path: Path) -> str:
    """Read a text file, tolerating UTF-16 (BOM or plain) and UTF-8 BOMs."""
    data = path.read_bytes()
    for bom, enc in ((b"\xff\xfe", "utf-16-le"), (b"\xfe\xff", "utf-16-be"), (b"\xef\xbb\xbf", "utf-8-sig")):
        if data.startswith(bom):
            return data.decode(enc, errors="replace")
    if b"\x00" in data[:512]:
        try:
            return data.decode("utf-16", errors="replace")
        except UnicodeError:
            pass
    return data.decode("utf-8", errors="replace")


def _key(node, *names):
    for name in names:
        value = node.get(name)
        if value is None:
            for k, v in node.items():
                if k.lower() == name.lower():
                    return v
    return None


def parse_soundbanks_json(path: Path, name_style: str, keep_hash: bool = False) -> List[Entry]:
    """Tolerant parser for Wwise 'SoundbanksInfo.json' / '(bank).json' files."""
    import json

    try:
        doc = json.loads(read_text_any(path))
    except ValueError as exc:
        print(f"warning: {path}: {exc}", file=sys.stderr)
        return []
    entries: List[Entry] = []

    def walk(node) -> None:
        if isinstance(node, dict):
            ident = _key(node, "Id", "id")
            if ident is not None and str(ident).isdigit():
                short = _key(node, "ShortName", "shortName", "name")
                pathv = _key(node, "Path", "path")
                name = _key(node, "Name", "name")
                if "IncludedEvents" in node or "IncludedMemoryFiles" in node:
                    entries.append(Entry(int(ident), str(short or pathv or ident),
                                         path.name, "bank"))
                elif pathv or (short and str(short).lower().endswith((".wem", ".wav", ".ogg", ".xma", ".bnk"))):
                    candidates = [pathv, short] if name_style == "path" else [short, pathv]
                    for cand in candidates:
                        if not cand:
                            continue
                        base = Path(str(cand).replace("\\", "/")).name
                        stem = Path(base).stem or base
                        if not keep_hash:
                            stem = HASH_SUFFIX_RE.sub("", stem)
                        if stem:
                            entries.append(Entry(int(ident), stem, path.name, "media"))
                            break
                elif name:
                    entries.append(Entry(int(ident), str(name), path.name, "event"))
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(doc)
    return entries

def parse_soundbanks_xml(path: Path, name_style: str, keep_hash: bool = False) -> List[Entry]:
    import xml.etree.ElementTree as ET

    root = ET.parse(str(path)).getroot()
    entries: List[Entry] = []

    for sb in root.iter("SoundBank"):
        sid = sb.get("Id")
        if not sid:
            continue
        nm = sb.findtext("ShortName") or sb.findtext("Path") or sid
        entries.append(Entry(int(sid), nm.strip(), path.name, "bank"))

    for ev in root.iter("Event"):
        eid = ev.get("Id")
        nm = ev.get("Name")
        if eid and nm:
            entries.append(Entry(int(eid), nm.strip(), path.name, "event"))

    for f in root.iter("File"):
        fid = f.get("Id")
        if not fid:
            continue
        nm = _media_name(f, name_style, keep_hash)
        if nm:
            entries.append(Entry(int(fid), nm, path.name, "media"))
    return entries


def _media_name(node, style: str, keep_hash: bool = False) -> Optional[str]:
    if style == "object":
        value = node.findtext("ObjectPath") or node.get("Name") or ""
        base = Path(value.replace("\\", "/")).name
        return base or None
    order = ("Path", "ShortName") if style == "path" else ("ShortName", "Path")
    for tag in order:
        value = (node.findtext(tag) or "").strip()
        if not value:
            continue
        base = Path(value.replace("\\", "/")).name
        stem = Path(base).stem or base
        if not keep_hash:
            stem = HASH_SUFFIX_RE.sub("", stem)
        if stem:
            return stem
    return None


def parse_ids_header(path: Path) -> List[Entry]:
    entries: List[Entry] = []
    pattern = re.compile(
        r"^\s*(?:static\s+)?(?:const\s+)?(?:AkUniqueID|AkUInt32|AkUInt32_t|unsigned\s+int)\s+"
        r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:\([^)]*\)\s*)?(\d+)\s*[UuLl]*\s*;"
    )
    define = re.compile(r"^\s*#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(\d+)\s*[UuLl]*\s*$")
    for raw in read_text_any(path).splitlines():
        m = pattern.match(raw) or define.match(raw)
        if m:
            entries.append(Entry(int(m.group(2)), m.group(1), path.name, "event"))
    return entries


def parse_bank_txt(path: Path) -> List[Entry]:
    """Best effort parser for Wwise '(bank).txt' style ID/name lists."""
    entries: List[Entry] = []
    for raw in read_text_any(path).splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "//")):
            continue
        tokens = [t for t in re.split(r"\t|\s{2,}", line) if t.strip()]
        if len(tokens) < 2:
            tokens = line.split(None)
        if len(tokens) < 2:
            continue
        id_token = None
        name_tokens = []
        for token in tokens:
            token = token.strip()
            if DEC_RE.match(token) and id_token is None and len(token) <= 10:
                id_token = token
            elif "\u3000" not in token:
                name_tokens.append(token)
        if id_token is None or not name_tokens:
            continue
        # prefer the last token (usually the name), else the longest
        cand = name_tokens[-1] if NAME_RE.match(name_tokens[-1]) else max(name_tokens, key=len)
        if NAME_RE.match(cand):
            entries.append(Entry(int(id_token), cand, path.name, "event"))
    return entries


def parse_wwnames(path: Path) -> List[Entry]:
    entries: List[Entry] = []
    for raw in read_text_any(path).splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if EXT_PATH_RE.match(line):  # external source path (64-bit FNV of the path)
            rel = line.replace("\\", "/")
            entries.append(Entry(wwise_external_hash(rel), Path(rel).stem, path.name, "external", rel))
            continue
        m = re.match(r"^(\d{1,10})\s*:\s*(.+)$", line)
        if m:
            name = m.group(2).strip()
            if NAME_RE.match(name):
                entries.append(Entry(int(m.group(1)), name, path.name, "wwnames"))
            continue
        if NAME_RE.match(line):
            entries.append(Entry(wwise_hash(line), line, path.name, "wwnames"))
    return entries


def parse_txtp_dir(path: Path) -> List[Entry]:
    entries: List[Entry] = []
    for txtp in sorted(path.glob("*.txtp")):
        name = txtp.stem.strip()
        # drop wwiser state markers: " {r}" / " (StateGroup_X=Y) [123=456]" etc.
        name = re.sub(r"\s*\{[^}]*\}", "", name)
        name = re.sub(r"\s*\([^)]*\)", "", name)
        name = re.sub(r"\s*\[[^\]]*\]", "", name).strip()
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)-(\d+)-event$", name)
        kind = "txtp"
        if m:
            # unnamed event: bank/name + node index still identifies it
            name = f"{m.group(1)}-{m.group(2)}"
            kind = "txtp-index"
        if not name or not re.match(r"^[A-Za-z_][A-Za-z0-9_-]*$", name):
            continue
        seen = set()
        for raw in read_text_any(txtp).splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" in line:
                continue  # comments / config lines
            for m in re.finditer(r"##([0-9]{1,10})\.wem|(?<!#)([0-9]{1,10})\.wem", line):
                mid = int(m.group(1) or m.group(2))
                if mid in seen:
                    continue
                seen.add(mid)
                entries.append(Entry(mid, name, str(txtp), "txtp"))
    return entries


def load_source(path: Path, name_style: str, keep_hash: bool = False) -> List[Entry]:
    if path.is_dir():
        return parse_txtp_dir(path)
    suffix = path.suffix.lower()
    if suffix == ".xml":
        return parse_soundbanks_xml(path, name_style, keep_hash)
    if suffix == ".json":
        return parse_soundbanks_json(path, name_style, keep_hash)
    if suffix in (".h", ".hpp", ".hxx", ".cs"):
        return parse_ids_header(path)
    if suffix == ".txtp":
        return parse_txtp_dir(path.parent) if path.parent else []
    if suffix in (".txt", ".tsv", ".lst"):
        # each text parser is strict, so simply merge what matches
        return parse_bank_txt(path) + parse_wwnames(path)
    return []


