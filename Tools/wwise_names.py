def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Rename <ShortID>.<ext> Wwise files to in-game names.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("sources", nargs="*", type=Path,
                        help="SoundbanksInfo.xml / Wwise_IDs.h / (bank).txt / wwnames.txt / .txtp dir")
    parser.add_argument("--audio-dir", type=Path, default=Path("."),
                        help="folder with ID-named files (default: current dir)")
    parser.add_argument("--ext", default=DEFAULT_EXTS,
                        help=f"extensions to rename (default: {DEFAULT_EXTS})")
    parser.add_argument("--recursive", action="store_true", help="scan subfolders too")
    parser.add_argument("--apply", action="store_true",
                        help="actually rename (default is a dry run)")
    parser.add_argument("--name-style", choices=("path", "short", "object"), default="path",
                        help="name used for media from SoundbanksInfo.xml "
                             "(path: original .wem path, short: ShortName, object: ObjectPath)")
    parser.add_argument("--keep-media-hash", action="store_true",
                        help="keep the generated _XXXXXXXX suffix in media names")
    parser.add_argument("--flat", action="store_true",
                        help="put externals directly in the audio dir instead of "
                             "recreating their original subfolders (e.g. English/voice)")
    parser.add_argument("--csv", type=Path, help="write the full ID -> name mapping as CSV")
    parser.add_argument("--fetch-wwnames", metavar="GAME TITLE",
                        help="download a prebuilt name list from wwiser-utils into ./wwnames.txt")
    args = parser.parse_args(argv)

    if args.fetch_wwnames:
        return fetch_wwnames(args.fetch_wwnames, Path("wwnames.txt"))

    if not args.sources:
        parser.error("no metadata sources given (or use --fetch-wwnames)")

    mapping: Dict[int, List[Entry]] = {}
    for src in args.sources:
        if not src.exists():
            print(f"skipping missing source: {src}", file=sys.stderr)
            continue
        entries = load_source(src, args.name_style, args.keep_media_hash)
        if not entries:
            print(f"warning: no names found in {src}", file=sys.stderr)
        for e in entries:
            bucket = mapping.setdefault(e.id, [])
            if not any(x.name == e.name and x.source == e.source for x in bucket):
                bucket.append(e)
        print(f"loaded {len(entries):6} names from {src}")

    if not mapping:
        print("no names loaded, nothing to do", file=sys.stderr)
        return 1

    exts = [e.strip().lower().lstrip(".") for e in args.ext.split(",") if e.strip()]
    plans, skipped_named, unresolved = build_plan(args.audio_dir, mapping, exts,
                                                  args.recursive, keep_paths=not args.flat)
    renamed, conflicts, errors = apply_plan(plans, args.apply, args.audio_dir)

    if args.csv:
        with args.csv.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.writer(fh)
            writer.writerow(["id", "id_style", "file", "new_path", "kind", "source", "alternatives"])
            for p in plans:
                target = _target_for(p, args.audio_dir)
                try:
                    shown = target.relative_to(args.audio_dir)
                except ValueError:
                    shown = target
                writer.writerow([p.id, p.id_style, p.path.name, str(shown),
                                 p.kind, p.source, "; ".join(p.alternatives)])
            for path, value, style in unresolved:
                writer.writerow([value, style, path.name, "", "", "UNRESOLVED", ""])
        print(f"mapping written to {args.csv}")

    if plans and not args.apply:
        print("\nplanned renames (dry run; pass --apply to execute):")
        for p in plans[:40]:
            target = _target_for(p, args.audio_dir)
            try:
                shown = target.relative_to(args.audio_dir)
            except ValueError:
                shown = target
            extra = f"   [alt: {p.alternatives[0]}]" if p.alternatives else ""
            print(f"  {p.path.name}  ->  {shown}  ({p.kind} / {p.source}){extra}")
        if len(plans) > 40:
            print(f"  ... and {len(plans) - 40} more (see --csv)")

    print()
    print(f"scanned          : {args.audio_dir}")
    print(f"ids with names   : {len(mapping)}")
    print(f"{'renamed' if args.apply else 'renameable':<17}: {renamed}"
          + (f" ({conflicts} name conflicts auto-suffixed)" if conflicts else ""))
    print(f"non-id files     : {skipped_named}")
    print(f"unresolved ids   : {len(unresolved)}")
    if unresolved:
        sample = ", ".join(f"{p.stem}" for p, _, _ in unresolved[:15])
        print(f"  sample: {sample}")
        print("  (reverse these with wwiser-utils' fnv.exe, or add a name list)")
    for err in errors:
        print(f"error: {err}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
