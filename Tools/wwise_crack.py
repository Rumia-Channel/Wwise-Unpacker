#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Recover Wwise names by harvesting candidate strings from game files and
testing them against the files' IDs.

Works for any Wwise game; two modes:

1. External sources (voice lines etc. named by path, 64-bit FNV-1 of the
   lowercased path). Point it at the ID-named files and give path templates:

     python wwise_crack.py --audio-dir voice/Audio --files "Game/Data" \
         --template "{lang}/voice/{token}.wem" --langs English Japanese \
         --out wwnames_cracked.txt

2. Event/object names (32-bit FNV-1 of the lowercased name). Point it at a
   folder of .txtp files generated by wwiser; the IDs are read from the
   "CAkEvent[n] <id>" lines and matched names are written as a name list that
   wwiser/wwise_names.py can consume:

     python wwise_crack.py --txtp txtp --files "Game/bin" "Game/Data" \
         --out wwnames_cracked.txt
     # then: wwiser.pyz banks/*.bnk -g ... (with wwnames.txt = that list)

Both modes are hash-verified, so a match is not a guess (64-bit collisions are
negligible; 32-bit collisions are possible but rare).

Candidate tokens come from anywhere the game keeps strings: data tables,
scripts, metadata, executables. `--prefix` narrows the pool for huge harvests,
`--expand N` also tries name_1..name_N / name1..N suffixes.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Set

MASK32 = 0xFFFFFFFF
MASK64 = 0xFFFFFFFFFFFFFFFF
FNV32_OFFSET = 0x811C9DC5
FNV32_PRIME = 0x01000193
FNV64_OFFSET = 0xCBF29CE484222325
FNV64_PRIME = 0x100000001B3

DEFAULT_TOKEN_RE = rb"[A-Za-z][A-Za-z0-9_]{4,64}"
DEFAULT_EVENT_RE = r"CAkEvent\[\d+\]\s+(\d+)"
DEFAULT_PREFIXES = ["play_", "Play_", "PLAY_", "stop_", "Stop_", "ev_", "Ev_", "EV_",
                    "ui_", "UI_", "sfx_", "SFX_", "music_", "Music_", "amb_", "Amb_",
                    "vo_", "VO_", "_"]
DEFAULT_SUFFIXES = ["_01", "_1", "_play", "_start", "_stop", "_music", "_sfx", "_amb",
                    "_idle", "_loop", "_main"]
HEX_RE = re.compile(r"^(?:0x)?([0-9a-fA-F]{9,16})$")
DEC_RE = re.compile(r"^\d{1,20}$")


def fnv1_32(text: str) -> int:
    h = FNV32_OFFSET
    for b in text.lower().encode("utf-8"):
        h = (h * FNV32_PRIME) & MASK32
        h ^= b
    return h


def fnv1_64(text: str) -> int:
    h = FNV64_OFFSET
    for b in text.lower().encode("utf-8"):
        h = (h * FNV64_PRIME) & MASK64
        h ^= b
    return h


def stem_id(stem: str) -> Optional[int]:
    """IDs as written by extractors: decimal (maybe signed) or 8/16 hex digits."""
    if HEX_RE.match(stem):
        return int(stem, 16)
    if DEC_RE.match(stem):
        value = int(stem)
        return value if value <= MASK64 else None
    return None


def collect_ids(audio_dir: Path, recursive: bool) -> Set[int]:
    it = audio_dir.rglob("*") if recursive else audio_dir.glob("*")
    ids = set()
    for path in it:
        if path.is_file():
            value = stem_id(path.stem)
            if value is not None:
                ids.add(value)
    return ids


def collect_txtp_ids(txtp_dir: Path, id_regex: str, recursive: bool) -> Set[int]:
    pattern = re.compile(id_regex)
    it = txtp_dir.rglob("*.txtp") if recursive else txtp_dir.glob("*.txtp")
    ids = set()
    for path in it:
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in pattern.finditer(text):
            ids.add(int(m.group(1)))
    return ids


def harvest(files: Sequence[Path], token_re: bytes, prefix: Optional[re.Pattern],
            min_len: int) -> Set[str]:
    tokens: Set[str] = set()
    pattern = re.compile(token_re)
    for target in files:
        if not target.exists():
            print(f"warning: missing {target}", file=sys.stderr)
            continue
        paths: Iterable[Path] = [target] if target.is_file() else \
            (p for p in target.rglob("*") if p.is_file())
        for path in paths:
            try:
                data = path.read_bytes()
            except OSError as exc:
                print(f"warning: cannot read {path}: {exc}", file=sys.stderr)
                continue
            for m in pattern.finditer(data):
                token = m.group(0).decode("ascii", "ignore")
                if len(token) >= min_len and (prefix is None or prefix.match(token)):
                    tokens.add(token)
    return tokens


def expand(tokens: Set[str], count: int) -> Set[str]:
    """Also try name_1..name_N / name1..N / name_01..N / name01..N suffixes."""
    if count <= 0:
        return tokens
    out = set(tokens)
    for token in tokens:
        for i in range(1, count + 1):
            out.add(f"{token}_{i}")
            out.add(f"{token}{i}")
            out.add(f"{token}_{i:02d}")
            out.add(f"{token}{i:02d}")
    return out


def read_token_list(path: Path, min_len: int) -> Set[str]:
    out = set()
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", line) and len(line) >= min_len:
            out.add(line)
    return out


def make_variants(tokens: Set[str], prefixes: Sequence[str], suffixes: Sequence[str],
                  limit: int) -> Set[str]:
    affixes_p = [""] + [p for p in prefixes if p]
    affixes_s = [""] + [s for s in suffixes if s]
    bare = [t for t in tokens if t not in ("", "_")]
    estimated = len(bare) * len(affixes_p) * len(affixes_s)
    if estimated > limit:
        print(f"warning: variant generation needs ~{estimated:,} candidates "
              f"(limit {limit:,}); narrowing with --prefix is recommended", file=sys.stderr)
    out = set(tokens)
    for token in bare:
        for prefix in affixes_p:
            for suffix in affixes_s:
                if prefix or suffix:
                    out.add(f"{prefix}{token}{suffix}")
    return out


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--audio-dir", type=Path,
                        help="folder with ID-named files (external/64-bit mode)")
    parser.add_argument("--txtp", type=Path, nargs="+", default=[],
                        help="folder(s) of wwiser .txtp files (name/32-bit mode)")
    parser.add_argument("--files", type=Path, nargs="+", default=[],
                        help="files/folders to harvest candidate strings from")
    parser.add_argument("--template", action="append", default=[],
                        help="path template with {token} (and optionally {lang}); external mode")
    parser.add_argument("--langs", nargs="*", default=[""],
                        help="values for {lang} (default: empty)")
    parser.add_argument("--id-regex", default=DEFAULT_EVENT_RE,
                        help="regex with one capture group for IDs inside .txtp files")
    parser.add_argument("--prefix", default=None, help="only harvest tokens matching this regex")
    parser.add_argument("--min-len", type=int, default=5)
    parser.add_argument("--token-regex", default=DEFAULT_TOKEN_RE.decode(),
                        help="byte regex used to harvest tokens")
    parser.add_argument("--tokens-from", type=Path, nargs="+", default=[],
                        help="text files with candidate names (e.g. bank/object names), one per line")
    parser.add_argument("--variants", action="store_true",
                        help="also try common affixes around the candidates (play_, _01, ...)")
    parser.add_argument("--prefixes", nargs="*", default=DEFAULT_PREFIXES,
                        help="affixes used by --variants")
    parser.add_argument("--suffixes", nargs="*", default=DEFAULT_SUFFIXES,
                        help="affixes used by --variants")
    parser.add_argument("--max-candidates", type=int, default=50_000_000,
                        help="warn when variant generation exceeds this many candidates")
    parser.add_argument("--expand", type=int, default=0,
                        help="also try name_1..name_N / name1..N suffixes")
    parser.add_argument("--recursive", action="store_true", help="scan subfolders too")
    parser.add_argument("--out", type=Path, default=Path("wwnames_cracked.txt"),
                        help="name list to write (default: wwnames_cracked.txt)")
    args = parser.parse_args(argv)

    if args.txtp:
        ids = set()
        for d in args.txtp:
            ids |= collect_txtp_ids(d, args.id_regex, True)
        mode = "name"
    elif args.audio_dir:
        ids = collect_ids(args.audio_dir, args.recursive)
        mode = "external"
        if not args.template:
            parser.error("external mode needs --template (e.g. \"{lang}/voice/{token}.wem\")")
    else:
        parser.error("give --audio-dir (external mode) or --txtp (name mode)")

    if not ids:
        print("no IDs found", file=sys.stderr)
        return 1
    print(f"mode: {mode} | target ids: {len(ids)}")

    prefix = re.compile(args.prefix) if args.prefix else None
    tokens = harvest(args.files, args.token_regex.encode(), prefix, args.min_len)
    for lst in args.tokens_from:
        if not lst.exists():
            print(f"warning: missing {lst}", file=sys.stderr)
            continue
        tokens |= read_token_list(lst, args.min_len)
    if args.variants:
        tokens = make_variants(tokens, args.prefixes, args.suffixes, args.max_candidates)
    tokens = expand(tokens, args.expand)
    if not tokens:
        print("no candidate tokens (pass --files and/or --tokens-from)", file=sys.stderr)
        return 1
    print(f"candidate tokens: {len(tokens)}")

    found: Dict[int, str] = {}
    tried = 0
    if mode == "name":
        for token in tokens:
            tried += 1
            h = fnv1_32(token)
            if h in ids and h not in found:
                found[h] = token
    else:
        for template in args.template:
            for lang in args.langs or [""]:
                tmpl = template.replace("{lang}", lang)
                for token in tokens:
                    candidate = tmpl.replace("{token}", token)
                    tried += 1
                    h = fnv1_64(candidate)
                    if h in ids and h not in found:
                        found[h] = candidate

    print(f"candidates tested: {tried}")
    print(f"recovered: {len(found)}/{len(ids)}")
    if found:
        lines = sorted(found.values())
        args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"name list written to {args.out}")
        for line in lines[:10]:
            print(f"   {line}")
        if len(lines) > 10:
            print(f"   ... and {len(lines) - 10} more")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
